def grid_macros():
    """Counts describing the grid-membership inference, after the Holm correction.

    The manuscript said "nine of ten powered arms reject" and named the wrong two arms as
    the exceptions: the two it named have no power at all, while the arm that actually
    fails the correction (900/s, raw 0.044, adjusted 0.131) was printed as a rejection.
    The count and the exception are therefore both derived here.
    """
    try:
        import stat_intervals
        cells = stat_intervals.grid_cells()
    except (ImportError, OSError, KeyError, ValueError):
        return []
    powered = [c for c in cells if c["powered"]]
    reject = [c for c in powered if c["verdict"] == "grid"]
    unresolved = [c for c in powered if c["verdict"] == "not resolved"]
    out = [
        ("gridArms", str(len(cells))),
        ("gridPowered", str(len(powered))),
        ("gridReject", str(len(reject))),
        ("gridFlat", str(sum(1 for c in cells if not c["powered"]))),
        # The supplement's caption said 10^4 draws and the committed artefact was written
        # with 4,000. Nobody noticed, because the floor of a Monte Carlo p-value sits far
        # below every threshold the paper uses; the caption was still wrong, and the number
        # of draws is the kind of thing a reader recomputing the test needs exactly.
        ("gridDraws", latex_thousands(grid_membership_test.MC_ARMS)),
    ]
    if unresolved:
        u = unresolved[0]
        out += [
            ("gridUnresolvedRate", str(u["rate_hz"])),
            ("gridUnresolvedRaw", "%.3f" % u["p_raw"]),
            ("gridUnresolvedHolm", "%.3f" % u["p_holm"]),
        ]
        # Where this arm's marker actually sits against its own bar. Round 49 found
        # Figure 4's caption disposing of it with "it sits at the edge of its bar rather
        # than below it" while the ledger puts it *below*: 0.2647 against a null band
        # opening at 0.2680. The caption had just told the reader that below means the arm
        # rejects, so the sentence meant to excuse the one non-rejecting arm classified it
        # as a rejection.
        #
        # The word is emitted rather than written because the caption's whole job here is
        # to say which side of the bar the marker is on, and that is a fact about the
        # committed null. A gap of 0.0033 is under a point at print size, so the eye cannot
        # settle it and neither could a proofreader.
        if u.get("d_observed") is not None and u.get("d_null_lo") is not None:
            side = ("below" if u["d_observed"] < u["d_null_lo"] else
                    "above" if u["d_observed"] > u["d_null_hi"] else "inside")
            out += [
                ("gridUnresolvedObs", "%.4f" % u["d_observed"]),
                ("gridUnresolvedNullLo", "%.4f" % u["d_null_lo"]),
                ("gridUnresolvedSide", side),
            ]
    flat = [c for c in cells if not c["powered"]]
    if len(flat) == 2:
        out.append(("gridFlatRates", "$%d$ and $%d$" % tuple(sorted(c["rate_hz"] for c in flat))))
    return out


def _fmt_p(value):
    return "$<0.001$" if value < 0.001 else "$%.3f$" % value


def render_grid_table():
    """Table II, generated from the artefact.

    The table was transcribed once and drifted from the correction its own caption
    claimed. A generated table cannot: the p-values it prints are the adjusted ones the
    caption promises, and the verdict column is a function of them.
    """
    import stat_intervals
    cells = stat_intervals.grid_cells()
    lines = [
        "% Generated by scripts/emit_paper_numbers.py from",
        "% docs/results/external/grid_membership.csv. Do not edit by hand.",
        "\\begin{tabular}{@{}rlrrrrl@{}}",
        "\\toprule",
        "rate & $p/q$ & $n$ & $D$ & null & $p_{\\mathrm{Holm}}$ & verdict \\\\",
        "\\midrule",
    ]
    for c in cells:
        lines.append("$%d$/s & $%d/%d$ & $%d$ & $%.3f$ & $%.3f$ & %s & %s \\\\"
                     % (c["rate_hz"], c["p"], c["q"], c["n"], c["d_observed"],
                        c["d_null"], _fmt_p(c["p_holm"]), c["verdict"]))
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def render_spread_table():
    """The quantisation table of S23, generated, with the column it was missing.

    The hand-written version this replaces was correct and stayed correct, because the test
    suite recomputed q, n, width, position, predicted class and agreement from the ledger on
    every run. But it printed the prediction and the measured spread and stopped there, so
    the *measured class* -- the column that turns "predicted full, spread 10.70, cell 14.29"
    into the word "full" -- existed only inside the gate. The sentence the table supports is
    a claim about agreement, and agreement was the one thing its reader had to take on
    trust while the machine checked it in private.

    So: same table, same label, same rows, one more column, and generated rather than typed.
    The q column carries the argument on its own -- at this operating point the continuous
    value sits at a half, which lies on every even grid and no odd one, so odd denominators
    are predicted full and even ones flat before any arm is run.
    """
    import stat_intervals
    cells = stat_intervals.spread_cells()
    lines = [
        "% Generated by scripts/emit_paper_numbers.py from",
        "% docs/results/external/phase_quantisation.csv. Do not edit by hand.",
        "\\begin{tabular}{@{}rlrrrrlrl@{}}",
        "\\toprule",
        "rate & $\\Delta/\\tau$ & $q$ & $n$ & width & pos. & predicts & spread & shows \\\\",
        "\\midrule",
    ]
    seen_incommensurate = False
    for c in cells:
        if not c["commensurate"] and not seen_incommensurate:
            seen_incommensurate = True
            lines += [
                "\\midrule",
                "\\multicolumn{9}{@{}l}{\\emph{incommensurate --- phase set effectively "
                "continuous}} \\\\",
            ]
        ratio = "$%d/%d$" % (c["p"], c["q"])
        if c["commensurate"]:
            # A disagreeing row is marked in the row itself. The caption named the two arms
            # and the table gave the eye nothing to find them with: twelve rows of "full" and
            # "flat" in adjacent columns is the hardest discrimination a table can ask for,
            # since the words are the same length, start with the same letter and are set in
            # the same face. The dagger does what the caption was doing alone.
            mark = "" if c["agrees"] else "$^{\\dagger}$"
            shows = c["observed"] if c["agrees"] else "\\textbf{%s}" % c["observed"]
            lines.append("$%d$/s%s & %s & $%d$ & $%d$ & $%.1f$ & $%.2f$ & %s & $%.1f$ & %s \\\\"
                         % (c["rate_hz"], mark, ratio, c["q"], c["n"], c["cell_width"],
                            c["position"], c["predicted"], c["spread"], shows))
        else:
            lines.append("$%d$/s & %s & ${>}%d$ & $%d$ & --- & --- & $\\approx 0$ & $%.1f$ "
                         "& --- \\\\"
                         % (c["rate_hz"], ratio, stat_intervals.INCOMMENSURATE_Q, c["n"],
                            c["spread"]))
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def spread_macros():
    """The counts S31 states in words, so the sentence and the table cannot drift apart.

    The sentence used to read "All nine commensurate arms match --- seven full, two flat",
    and every number in it was typed. It was true of the ledger it was written against, and
    that ledger had stopped being what the code produces: `phase_quantisation.csv` was built
    before chain17's `ultimate` campaign joined RATE_CAMPAIGNS and was never rebuilt, so the
    manuscript's strongest sentence rested on a nine-arm corpus its own analyser no longer
    emits. Rebuilt, the corpus is twelve arms and ten of them match.

    Note the shape change, which is why these are separate macros now. At nine arms the
    agreement count and the prediction breakdown coincided -- nine matched, and the
    predictions were seven full and two flat -- so one sentence could carry both and nobody
    had to say which was which. At twelve they part: ten arms match, and separately ten are
    predicted full against two predicted flat. Two numbers that happen to be equal for two
    different reasons is exactly the coincidence a typed sentence preserves and a generated
    one cannot.
    """
    try:
        import stat_intervals
        every = stat_intervals.spread_cells()
        cells = [c for c in every if c["commensurate"]]
        loose = [c for c in every if not c["commensurate"]]
    except (ImportError, OSError, KeyError, ValueError):
        return []
    if not cells:
        return []
    miss = [c for c in cells if not c["agrees"]]
    out = [
        ("spreadArms", "%d" % len(cells)),
        ("spreadAgree", "%d" % (len(cells) - len(miss))),
        ("spreadMissWord", _spell(len(miss))),
        ("spreadMissRates", _join_rates(sorted(c["rate_hz"] for c in miss))),
        ("spreadPredFullWord", _spell(sum(1 for c in cells if c["predicted"] == "full"))),
        ("spreadPredFlatWord", _spell(sum(1 for c in cells if c["predicted"] == "flat"))),
    ]
    # The incommensurate arms and where their medians land. Section V-B read "Both
    # incommensurate arms sit near 50%" of a corpus that has seven of them, all near 50 --
    # a sentence that understated its own evidence three and a half fold because the count
    # was typed when the corpus had two.
    if loose:
        medians = sorted(c["median"] for c in loose)
        out += [
            ("spreadIncommensurate", "%d" % len(loose)),
            ("spreadIncommensurateWord", _spell(len(loose))),
            ("spreadIncommensurateLo", "%.1f" % medians[0]),
            ("spreadIncommensurateHi", "%.1f" % medians[-1]),
        ]
    # The corrected p-values of exactly the arms the spread rule misses. S31 turns on these
    # two numbers -- the replacement statistic resolving what the superseded one could not --
    # so they are taken from the grid-membership artifact rather than read off its table.
    try:
        holm = {c["rate_hz"]: c["p_holm"] for c in stat_intervals.grid_cells()}
    except (OSError, KeyError, ValueError):
        return out
    for c in miss:
        p = holm.get(c["rate_hz"])
        if p is not None:
            out.append(("pgrid%s" % _spell_rate(c["rate_hz"]), _fmt_p(p)))
    return out


