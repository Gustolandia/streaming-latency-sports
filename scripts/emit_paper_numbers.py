"""
emit_paper_numbers.py
Derive the manuscript's campaign numbers from the ledger instead of typing them.

The run count for the external campaign appeared in the manuscript in nine places and the discard
total in two. When the campaign grew, all eleven went stale together: the paper said `$80$ runs`
and `roughly $420{,}000$ discarded` when the ledger held `108` and `4{,}377{,}904`. Being wrong by
a factor of ten in a section whose entire argument is that benchmarks misreport their own sample
counts is not a typo, it is the paper committing the error it documents.

Hand-editing eleven sites is what created the problem, so this does not do that. It writes LaTeX
macros, the manuscript uses the macros, and the number exists once. `--check` verifies the
committed file still agrees with the ledger without rewriting it, so a build can gate on it.

The quantities are computed by `check_paper_omb_numbers.measured`, imported rather than
reimplemented -- two copies of this arithmetic would drift, and the drift would be invisible
because both would look authoritative.

CLI:
    python scripts/emit_paper_numbers.py
    python scripts/emit_paper_numbers.py --check
"""
