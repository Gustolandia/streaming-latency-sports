def latex_thousands(n):
    """12345678 -> 12{,}345{,}678, the separator that survives LaTeX's math mode."""
    return "{,}".join(_chunks(str(int(n))))


def _chunks(s):
    """Digit groups of three, counted from the right."""
    head = len(s) % 3 or 3
    return [s[:head]] + [s[i:i + 3] for i in range(head, len(s), 3)]


def macros(m):
    """The (name, value) pairs the manuscript may reference.

    Names are deliberately verbose. A macro called `\\n` in a 3000-line manuscript is a trap, and
    a macro whose name does not say which campaign it counts is the same trap one level up.

    The Kafka/Redis split exists because the negative-sample story is scoped: the withdrawal
    rests on the Kafka-driver corpus staying at zero negatives, while the Redis-driver
    replication caught real ones. One unsplit total let a claim about one corpus be silently
    contradicted by the other.
    """
    out = [
        ("ombRuns", str(m["n_runs"])),
        ("ombDiscarded", latex_thousands(m["discarded_total"])),
        ("ombKept", latex_thousands(m["kept_total"])),
        ("ombNegatives", latex_thousands(m["negatives"])),
        ("ombKafkaRuns", str(m["kafka_runs"])),
        ("ombKafkaDiscarded", latex_thousands(m["kafka_discarded"])),
        ("ombKafkaNegatives", latex_thousands(m["kafka_negatives"])),
        ("ombRedisRuns", str(m["redis_runs"])),
        ("ombRedisDiscarded", latex_thousands(m["redis_discarded"])),
        ("ombRedisNegatives", latex_thousands(m["redis_negatives"])),
    ]
    if m.get("redis_worst_negatives") is not None:
        out += [
            ("ombRedisWorstNegatives", latex_thousands(m["redis_worst_negatives"])),
            ("ombRedisWorstKept", _spell(m["redis_worst_kept"])
             if m["redis_worst_kept"] <= 12 else latex_thousands(m["redis_worst_kept"])),
        ]
    if m["retention_min"] is not None:
        out.append(("ombRetentionMin", "%.2f" % m["retention_min"]))
        out.append(("ombRetentionMinExact", "%.4f" % m["retention_min"]))
    if m["retention_max"] is not None:
        out.append(("ombRetentionMax", "%.2f" % m["retention_max"]))
    return out


def span_macros(path=SPAN_CSV):
    """Negatives per span, from the committed recount.

    These exist because the manuscript spent two versions calling one span's negatives a
    causality violation. The correction is not a rewording: the acknowledgement-referenced
    span and the send-referenced span disagree, and only the first goes negative. A claim
    that specific has to be recomputed from the artefact every time the paper is built.

    Returns [] when the recount is absent, so a checkout without it still emits the campaign
    numbers; the manuscript's own tests are what forbid quoting a macro that does not exist.
    """
    if not os.path.exists(path):
        return []
    agg = recount_spans.totals(recount_spans.read_csv(path))
    out = [
        ("spanRuns", latex_thousands(agg["runs"])),
        ("spanEvents", latex_thousands(agg["events"])),
        ("spanNegAck", latex_thousands(agg["neg_ack"])),
        ("spanNegAckPct", "%.2f" % agg["pct_ack"]),
        ("spanNegSend", latex_thousands(agg["neg_send"])),
        ("spanNegOutputSend", latex_thousands(agg["neg_output_send"])),
        ("spanNegTti", latex_thousands(agg["neg_tti"])),
        ("spanRunsOverOnePct", latex_thousands(agg["runs_over_one_pct_ack"])),
        ("spanRunsAckOnly", latex_thousands(agg["runs_ack_only_inversions"])),
        # Conditioned on the runs that invert at all. Dividing by the whole corpus instead
        # buries the result: the runs where nothing inverted carry no information either way,
        # and including them turned 100% into 77%.
        ("spanRunsAckInverts", latex_thousands(agg["runs_ack_inverts"])),
        ("spanRunsAckOnlyPct", "%.0f" % (
            100.0 * agg["runs_ack_only_inversions"] / agg["runs_ack_inverts"]
            if agg["runs_ack_inverts"] else 0.0)),
        ("spanRunsSendInverts", latex_thousands(agg["runs_send_inverts"])),
        # The margin that does the actual excluding.
        ("spanDeepestInversionMs", "%.1f" % (agg["deepest_ack_inversion_us"] / 1000.0)),
        ("spanSendFloorUs", "%.0f" % agg["send_span_floor_us"]),
        ("spanOffsetMargin", "%.0f" % agg["offset_margin_factor"]),
    ]
    # Per-backend, because pooling hides the only control that separates "a property of
    # Kafka's client" from "a property of an acknowledgement-referenced span". Both backends
    # stamp on one host and one clock, so the broker is the sole variable across the columns.
    #
    # Only what the manuscript quotes is emitted. A generated file carrying macros nobody
    # reads is a place for a stale number to survive a revision, and the split already has
    # more counters than the text needs.
    rows = recount_spans.read_csv(path)
    split = recount_spans.by_backend(rows)
    floors = []
    for backend, agg in split.items():
        key = backend[:1].upper() + backend[1:]
        if not key.isalpha():  # macro names are LaTeX control words
            continue
        floors.append(agg["send_span_floor_us"])
        out.extend([
            ("span%sEvents" % key, latex_thousands(agg["events"])),
            ("span%sNegAck" % key, latex_thousands(agg["neg_ack"])),
            ("span%sNegAckPct" % key, "%.2f" % agg["pct_ack"]),
            ("span%sRunsAckInvertsPct" % key, "%.0f" % (
                100.0 * agg["runs_ack_inverts"] / agg["runs"] if agg["runs"] else 0.0)),
        ])
        # The consumer's own handling span, which is where the two clients differ in what
        # falls inside the transport proxy. Nanoseconds for both, because one of them is two
        # adjacent clock reads and any coarser unit prints it as zero -- which is how the
        # asymmetry stayed invisible until round 43.
        if "median_output_ns" in agg:
            out.append(("span%sHandlingNs" % key,
                        latex_thousands(int(round(agg["median_output_ns"])))))
    handling = [agg["median_output_ns"] for agg in split.values()
                if "median_output_ns" in agg and agg["median_output_ns"] > 0]
    if len(handling) > 1:
        out.append(("spanHandlingRatio", "%.0f" % (max(handling) / min(handling))))
    # The pooled floor is the smaller of the two; the manuscript says so, so the other one
    # has to be a number it can print rather than a claim it makes.
    if len(floors) > 1:
        out.append(("spanSendFloorOtherUs", "%.0f" % max(floors)))
    return out


def traced_ratio_macros():
    """Traced-prediction over observed inversion, one ratio per arm that has both.

    These three numbers were typed into Section V-C. They are the paper's only unfitted
    cross-instrument check, and Section V-E now leans on them a second time: a kernel-only
    estimator that bracketed unity bounds any additional userspace delay between the wakeup
    and the clock read. A quantity carrying that much argument should not be hand-copied.

    The real-time arms floor at zero inversions, so they have no finite ratio and are
    skipped rather than reported as infinite.
    """
    import csv
    import glob
    ratios = []
    for path in sorted(glob.glob(os.path.join("docs", "results", "**", "runq_tail.csv"),
                                 recursive=True)):
        with open(path, encoding="utf-8", newline="") as fh:
            for row in csv.DictReader(fh):
                try:
                    inv = float(row["inversion"])
                    tail = float(row["p_tail"])
                except (KeyError, TypeError, ValueError):
                    continue
                if inv > 0:
                    ratios.append(tail / inv)
    if not ratios:
        return []
    ratios.sort()
    return [
        ("tracedRatios", ", ".join("%.2f" % r for r in ratios)),
        ("tracedRatioLo", "%.2f" % ratios[0]),
        ("tracedRatioHi", "%.2f" % ratios[-1]),
        ("tracedRatioArms", str(len(ratios))),
    ]


def stat_macros():
    """Interval estimates for the manipulation cells and the payload fit.

    The manuscript claims "disjoint Wilson intervals" and an effective exponent from four
    points. Both are checkable numbers, so both are emitted here rather than typed: a
    re-run that moves a cell moves the macro, and `--check` fails the build instead of
    letting the text and the artefact drift apart.

    Returns [] if the artefacts are absent, for the same reason span_macros() does.
    """
    try:
        import stat_intervals
    except ImportError:  # pragma: no cover - stat_intervals ships beside this file
        return []
    out = []
    try:
        cells = {lvl: (kb, nb, kr, nr) for lvl, kb, nb, kr, nr
                 in stat_intervals.priority_cells()}
    except (OSError, KeyError, ValueError):
        return []
    for level, name in (("l75", "Low"), ("l88", "High")):
        if level not in cells:
            continue
        kb, nb, kr, nr = cells[level]
        blo, bhi = stat_intervals.wilson(kb, nb)
        rlo, rhi = stat_intervals.wilson(kr, nr)
        z, ratio = stat_intervals.ratio_z(kb, nb, kr, nr)
        out += [
            ("rt%sBase" % name, "%.4f" % (kb / nb)),
            ("rt%sBaseCI" % name, "%.4f$--$%.4f" % (blo, bhi)),
            ("rt%sRt" % name, "%.4f" % (kr / nr)),
            ("rt%sRtCI" % name, "%.4f$--$%.4f" % (rlo, rhi)),
            ("rt%sFactor" % name, "%.0f" % round(ratio)),
            # The factor is what the discussion quotes, and until round 54 it was quoted
            # bare. The collapsed arms hold ten and seventeen events, so the interval is
            # wide and the omission flattered the result: 39x is really 21-74x.
            ("rt%sFactorCI" % name, "%.0f$--$%.0f" % stat_intervals.ratio_ci(kb, nb, kr, nr)),
            ("rt%sZ" % name, "%.1f" % z),
        ]
    # The geometry half of Table III was typed by hand while the priority half above came
    # from this function. Both halves make the same kind of claim from the same kind of
    # artefact, so both belong here: four rates, four intervals, two factors and two z's that
    # a re-run can move. Found while adding the figure that plots these same cells.
    for phase, name in (("ea6", "GeomOrig"), ("ea6b", "GeomRepl")):
        try:
            cells = stat_intervals.geometry_cells(phase)
        except (OSError, KeyError, ValueError):
            continue
        if len(cells) != 2:
            continue
        (_, kc, nc), (_, ks, ns) = cells
        clo, chi = stat_intervals.wilson(kc, nc)
        slo, shi = stat_intervals.wilson(ks, ns)
        z, ratio = stat_intervals.ratio_z(ks, ns, kc, nc)
        out += [
            ("%sConc" % name, "%.4f" % (kc / nc)),
            ("%sConcCI" % name, "%.4f$--$%.4f" % (clo, chi)),
            ("%sSpread" % name, "%.4f" % (ks / ns)),
            ("%sSpreadCI" % name, "%.4f$--$%.4f" % (slo, shi)),
            ("%sFactor" % name, "%.2f" % ratio),
            ("%sFactorCI" % name, "%.2f$--$%.2f" % stat_intervals.ratio_ci(ks, ns, kc, nc)),
            ("%sZ" % name, "%.1f" % abs(z)),
        ]
    # The endpoints of the same sweep the fit above runs on. Section V-C quoted all three of
    # these in one sentence, three other sentences quoted the transport ratio rounded to an
    # integer, and the figure recomputed it a sixth time -- every copy correct, none of them
    # reading any other. Two macros for the ratio, not one, because the paper genuinely wants
    # two precisions: the result sentence earns a decimal and the three summary sentences read
    # better rounded. Emitting both makes that a decision rather than an accident, and makes
    # `\payloadTransportFactorRound` provably the rounding of `\payloadTransportFactor`.
    try:
        span = stat_intervals.payload_span()
        out += [
            ("payloadTransportFactor", "%.1f" % span["transport_factor"]),
            ("payloadTransportFactorRound", "%.0f" % round(span["transport_factor"])),
            ("payloadRateFall", "%.1f" % span["rate_fall"]),
        ("payloadRateFallCI", "%.1f$--$%.1f" % span["rate_fall_ci"]),
            ("payloadRhoSpread", "%.3f" % span["rho_spread"]),
            ("payloadLevels", str(span["levels"])),
            # Two decimals for S25's comparison caption, which sets the two campaigns side by
            # side. A caption whose whole point is that two runs agree is the last place that
            # should hold typed copies of what they agree on.
            ("payloadRateFallExact", "%.2f" % span["rate_fall"]),
        ]
    except (OSError, KeyError, ValueError):
        pass
    try:
        repl = stat_intervals.payload_span("ea10b")
        out += [
            ("payloadReplTransportFactor", "%.1f" % repl["transport_factor"]),
            ("payloadReplRateFall", "%.2f" % repl["rate_fall"]),
        ("payloadReplRateFallCI", "%.2f$--$%.2f" % repl["rate_fall_ci"]),
        ]
    except (OSError, KeyError, ValueError):
        pass
    try:
        slope, intercept, r2, lo, hi = stat_intervals.payload_fit()
        npts = stat_intervals.payload_points()
        out += [
            ("tailExponent", "%.3f" % (-slope)),
            ("tailExponentCI", "%.3f$--$%.3f" % (-hi, -lo)),
            # Signed, for every place that says the word "slope". The magnitude above is for
            # the supplement's `T^{-\tailExponent}`, where the sign lives in the notation;
            # printing it beside a figure that draws the signed fit is how the paper came to
            # show 0.339 and -0.34 for one number on facing pages.
            ("tailSlope", "%.2f" % slope),
            # Self-mathed like every other CI here: the value is used inside $...$, closes
            # math around the word and reopens it, so the signs print as minus and
            # "to" prints roman. A bare hyphen in text mode would be neither.
            ("tailSlopeCI", "%.2f$ to $%.2f" % (lo, hi)),
            # The prefactor of the fitted power law, rate = C * T^(-alpha). The fit already
            # returns the intercept and the emitter was throwing it away, so the supplement
            # typed C out in three places: the one quantity in tail_index.csv with a
            # committed source and no macro, and therefore the one the ledger sweep of round
            # 24 could not see, because that sweep asks whether a macro'd value is read from
            # its macro and not whether a sourced value has one.
            ("tailPrefactor", "%.3f" % math.exp(intercept)),
            ("tailRsq", "%.3f" % r2),
            # The R-squared's own limit, emitted beside it. Four levels and two fitted
            # parameters leave two residual degrees of freedom, so 0.990 is close to what
            # arithmetic guarantees rather than a measure of how well the law holds. The
            # adjusted value is the same number told honestly. A gate refuses any use of
            # \tailRsq on the manuscript surface that does not also carry \tailRsqPoints,
            # which is what keeps a later draft from quoting the decoration on its own.
            ("tailRsqPoints", str(npts)),
            ("tailRsqDof", str(max(npts - 2, 0))),
            ("tailRsqAdj", "%.3f" % _adjusted_r2(r2, npts, 1)),
        ]
    except (OSError, KeyError, ValueError):
        pass
    return out


