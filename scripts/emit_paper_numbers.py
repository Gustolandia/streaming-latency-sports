def traced_macros():
    """The traced stall tail, estimated with intervals rather than eyeballed.

    The manuscript quoted a "windowed log-log index" off the same histogram and called it
    indistinguishable from the payload-sweep exponent. It is not an independent
    confirmation: a least-squares slope through four nested survival points returns a
    number whether or not the points lie on a line, and here the per-octave indices differ
    by two orders of magnitude, so no single index describes the window. Both the
    model-free estimate and the evidence against the power law are emitted.
    """
    try:
        import tail_index_traced
        rows = [r for r in tail_index_traced.report() if r.get("tag") == "ea9/l88_base"]
    except (ImportError, OSError, ValueError):
        return []
    if not rows:
        return []
    r = rows[0]
    out = [
        ("tracedEvents", latex_thousands(r["traced_events"])),
        ("tracedMleAlpha", "%.2f" % r["mle_alpha"]),
        ("tracedMleCI", "%.2f$--$%.2f" % (r["mle_lo"], r["mle_hi"])),
    ]
    if "exc_alpha" in r:
        out += [
            ("tracedExcAlpha", "%.2f" % r["exc_alpha"]),
            ("tracedExcCI", "%.2f$--$%.2f" % (r["exc_lo"], r["exc_hi"])),
        ]
    if len(r["octaves"]) >= 2:
        out += [
            ("tracedOctaveA", "%.2f" % r["octaves"][0][1]),
            ("tracedOctaveB", "%.2f" % r["octaves"][1][1]),
        ]
    top = [m for m in r.get("modes", []) if m[0] >= 1024]
    if top:
        lo, _, share, ratio = max(top, key=lambda m: m[1])
        # Where this mode sits among all the modes, by share. It is the one the paper argues
        # about, and it is *not* the biggest: the jitter core and the second mode both carry
        # more. Round 29 found the introduction calling it the "largest mode" against a figure
        # printing 20.0, 13.5 and 10.5 -- a claim about a ranking nothing had ever computed.
        # Emitting the rank lets a gate check the adjective, and lets it relax by itself if a
        # recomputation ever makes this mode the largest.
        by_share = sorted(r.get("modes", []), key=lambda m: m[2], reverse=True)
        rank = next(i for i, m in enumerate(by_share, 1) if m[0] == lo)
        out += [
            ("tracedModeLo", "%.0f" % (lo / 1024.0)),
            ("tracedModeHi", "%.0f" % (2 * lo / 1024.0)),
            ("tracedModeShare", "%.1f" % (100 * share)),
            ("tracedModeRatio", "%.1f" % ratio),
            ("tracedModes", str(len(r.get("modes", [])))),
            ("tracedModeRank", str(rank)),
            ("tracedModeTopShare", "%.1f" % (100 * by_share[0][2])),
        ]
    if "tail_alpha" in r:
        out += [
            ("tracedTailAlpha", "%.2f" % r["tail_alpha"]),
            ("tracedTailCI", "%.2f$--$%.2f" % (r["tail_lo"], r["tail_hi"])),
            ("tracedTailFrom", "%.0f" % (r["tail_from_us"] / 1024.0)),
        ]
    if "gof_p" in r and r["gof_boot"]:
        out += [
            ("tracedGofP", ("<%.4f" % (1.0 / r["gof_boot"])) if r["gof_p"] == 0
             else "%.3f" % r["gof_p"]),
            ("tracedGofBoot", latex_thousands(r["gof_boot"])),
        ]
    return out


