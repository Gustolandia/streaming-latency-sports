def render_priority_table():
    """Every matched pair, one row each, generated from the three campaign files.

    Transcription is what produced a two-row table that outlived the campaign by six pairs.
    """
    rows = priority_pairs.usable()
    lines = [
        "% Generated by scripts/emit_paper_numbers.py from",
        "% docs/results/model/stamping_priority*.csv. Do not edit by hand.",
        "\\begin{tabular}{@{}llrrrr@{}}",
        "\\toprule",
        "campaign & load & $\\rho$ & ordinary & real-time & factor \\\\",
        "\\midrule",
    ]
    for r in rows:
        lines.append("%s & $%s\\%%$ & $%.4f$ & $%.4f$ & $%.4f$ & $%.0f\\times$ \\\\"
                     % (r["campaign"], r["level"].lstrip("l"), r["rho"],
                        r["rate_base"], r["rate_rt"], r["factor"]))
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    return "\n".join(lines)


