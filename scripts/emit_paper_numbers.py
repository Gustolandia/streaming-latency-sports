def _tt(name):
    """Tool names that are literal command names are set in a monospace face."""
    literal = {"emqtt-bench", "fio"}
    if name in literal:
        return "\\texttt{%s}" % name.replace("_", "\\_")
    if name == "blktrace btt":
        return "\\texttt{blktrace/btt}"
    if name == "OpenMessaging Benchmark":
        return "OpenMessaging Bench."
    return name


def retention_macros():
    """The cells behind the deletion claim, and the denominator the manuscript lacked.

    "The 49 runs on an unsaturated path" matched no partition of the artefact. What the
    artefact supports is the set of cells whose reported median lands on the millisecond
    grid, which is both checkable and the sharper claim.
    """
    try:
        import stat_intervals
        cells = stat_intervals.retention_cells()
    except (ImportError, OSError, KeyError, ValueError):
        return []
