_SPELLED = ("zero", "one", "two", "three", "four", "five", "six",
            "seven", "eight", "nine", "ten", "eleven", "twelve")


def _spell(n):
    """A small count as a word, for prose. Above twelve, IEEE style takes the digits back."""
    return _SPELLED[n] if 0 <= n < len(_SPELLED) else str(n)


def registry_macros():
    """The audited-harness survey in Section II, counted rather than asserted.

    Every one of these is a fold over docs/results/external/harness_registry.csv whose class
    labels are recomputed from the committed evidence lines by the same classifier that read
    our own corpus. If a later edit loosens a pattern, these numbers move, the ledger check
    fails, and the sentence in Section II cannot be built until someone looks.
    """
    try:
        import harness_registry
        from audit_external_harness import DISPOSAL_KINDS
        s = harness_registry.summary()
    except (ImportError, OSError, KeyError, ValueError):
        return []
    out = [
        ("harnessAudited", str(s["harnesses"])),
        ("harnessVendors", str(s["vendors"])),
        ("harnessLanguages", str(s["languages"])),
        ("harnessEvidenceLines", str(s["evidence_lines"])),
        ("harnessSilent", str(s["n_silent"])),
        # Silent harnesses other than the audited subject itself: the count the text
        # uses for "independent tools", which round 6 caught as prose that only
        # happened to be right after the re-audit.
        ("harnessSilentIndependent",
         str(len([h for h in s["silent"] if h != "OpenMessaging Benchmark"]))),
        ("harnessFilters", str(len(s["filters"]))),
        ("harnessSuppressors", str(len(s["suppressors"]))),
        ("harnessCounting", str(len(s["counts_discards"]))),
        ("harnessRefusals", str(len(s["library_refusals"]))),
        # How many disposal classes there are, which the paragraph in IV-D was asserting from
        # prose and asserting wrongly: it said four while the taxonomy has three and the
        # sentence itself enumerated three. The size of DISPOSAL_KINDS is not a fact about
        # this campaign, it is a fact about the classifier, and it is countable.
        ("harnessDisposalClasses", str(len(DISPOSAL_KINDS))),
        # The tool in no disposal class at all. emqtt-bench guards a counter rather than the
        # sample, so it neither discards nor counts a discard, and lumping it with the tool
        # that counts is what left Section IV-D describing it as "a fifth entry" of nothing.
        ("harnessNoDisposal",
         str(s["harnesses"] - s["n_silent"] - len(s["counts_discards"]))),
    ]
    # Spelled forms of the same counts. IEEE house style wants a small number spelled in
    # prose; the alternative to emitting the word was transcribing it, which is the failure
    # mode this whole file exists to prevent.
    spelled = [(name, _spell(int(value))) for name, value in list(out)
               if name.startswith("harness") and value.isdigit() and int(value) <= 12]
    out += [(name + "Word", word) for name, word in spelled]
    # And the same word capitalised, because several of these open a sentence and a macro
    # cannot know that it does. Emitting both beats teaching the manuscript to remember.
    out += [(name + "WordCap", word[:1].upper() + word[1:]) for name, word in spelled]
    # The scope of the guard, computed rather than remembered. A referee who opens
    # MessageProducer.java finds a nanosecond clock and no filter, and will read an
    # unqualified "the benchmark filters" as overstated. These macros make the qualifier a
    # property of the evidence: which span is guarded, and which clock each span uses.
    try:
        contrast = harness_registry.within_harness_contrast()
    except (OSError, KeyError, ValueError):
        return out
    omb = contrast.get("OpenMessaging Benchmark")
    if omb:
        (gpath, gclock) = omb["guarded"][0]
        (upath, uclock) = omb["unguarded"][0]
        out += [
            ("ombGuardedPath", gpath),
            ("ombGuardedClock", gclock),
            ("ombUnguardedPath", upath),
            ("ombUnguardedClock", uclock),
        ]
    out.append(("harnessSplitGuard", str(len(contrast))))
    return out


