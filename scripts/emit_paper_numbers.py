def all_pairs(m):
    return (list(macros(m)) + span_macros() + stat_macros() + grid_macros()
            + retention_macros() + traced_macros() + tost_macros()
            + mechanism_macros() + kernel_macros() + registry_macros()
            + registry_sources_macro()
            + clocksource_macros() + traced_ratio_macros() + audit_macros()
            + priority_macros() + priority_residual_macros() + fork_macros())


def render(m):
    body = "".join("\\newcommand{\\%s}{%s}\n" % (name, val) for name, val in all_pairs(m))
    return HEADER + body


def main(argv=None):
    ap = argparse.ArgumentParser(description="Emit campaign numbers as LaTeX macros")
    ap.add_argument("--ledger", default=os.path.join("docs", "results",
                                                     "external_campaigns_index.csv"))
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--table", default=DEFAULT_TABLE)
    ap.add_argument("--registry-table", default=DEFAULT_REGISTRY_TABLE)
    ap.add_argument("--priority-table", default=DEFAULT_PRIORITY_TABLE)
    ap.add_argument("--check", action="store_true",
                    help="fail if the committed file disagrees with the ledger; write nothing")
    args = ap.parse_args(argv)

    if not os.path.exists(args.ledger):
        print("missing: %s" % args.ledger)
        return 1
    cells = load_cells(args.ledger)
    if not cells:
        print("no admissible cells in %s -- refusing to emit numbers from nothing" % args.ledger)
        return 1

    m = measured(cells)
    # Both generated files are gated together. The grid table was the one place a number
    # reached the page without passing through this script, and it is the one place the
    # paper contradicted its own caption.
    targets = [(args.out, render(m))]
    try:
        targets.append((args.table, render_grid_table()))
    except (ImportError, OSError, KeyError, ValueError) as exc:
        print("note: grid table not generated (%s)" % exc)
    reg = render_registry_table()
    if reg:
        targets.append((args.registry_table, reg))
    try:
        targets.append((args.priority_table, render_priority_table()))
    except (ImportError, OSError, KeyError, ValueError) as exc:
        print("note: priority table not generated (%s)" % exc)

    if args.check:
        stale = False
        for path, want in targets:
            if not os.path.exists(path):
                print("missing: %s (run without --check to create it)" % path)
                stale = True
                continue
            with open(path, encoding="utf-8") as fh:
                have = fh.read()
            if have.replace("\r\n", "\n") != want:
                print("STALE: %s disagrees with the artefacts" % path)
                stale = True
        if stale:
            print("  regenerate with: python scripts/emit_paper_numbers.py")
            return 1
        print("OK: %s generated file(s) match the artefacts" % len(targets))
        return 0

    for path, want in targets:
        parent = os.path.dirname(path)
        if parent:
            os.makedirs(parent, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(want)
        print("wrote %s" % path)
    for name, val in all_pairs(m):
        print("  \\%-22s %s" % (name, val))
    return 0


if __name__ == "__main__":  # pragma: no cover - dispatch only; main() is tested directly
    sys.exit(main())
