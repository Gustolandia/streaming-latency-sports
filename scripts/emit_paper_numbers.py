def disease_macros(path=os.path.join("docs", "results", "span_run_level.csv")):
    """The ladder: how much displacement the sign check does not fire on.

    A negative span needs A > D. Lengthening the path raises D and leaves A alone, so the
    check goes quiet on exactly the deployments whose delivery is slow enough to hide it --
    the visible negatives are the tip, and this is the rest of it. Emitted per event over the
    whole corpus, and the top rung is checked against the sign count as an identity: a ladder
    whose alpha=1 rung disagreed with the negatives would mean one of the two was wrong.

    Also the recovery estimator, split by gate outcome, because a correction that only works
    where the check already passes is not a correction.
    """
    import csv as _csv
    try:
        with open(path, encoding="utf-8") as fh:
            rows = list(_csv.DictReader(fh))
    except OSError:
        return []
    if not rows:
        return []
    total = sum(int(r["n_events"]) for r in rows)
    if not total:
        return []
    neg = sum(int(r["neg_ack"]) for r in rows)
    out = [("diseaseEvents", latex_thousands(total)),
           ("diseaseRuns", latex_thousands(len(rows)))]
    for col, name in (("over_0.1", "Tenth"), ("over_0.5", "Half"), ("over_1", "Whole")):
        if col in rows[0]:
            k = sum(int(r[col]) for r in rows)
            out.append(("diseaseOver" + name, "%.1f" % (100.0 * k / total)))
    # identity, not decoration: alpha = 1 IS the sign check
    if "over_1" in rows[0] and sum(int(r["over_1"]) for r in rows) != neg:
        raise ValueError("ladder top rung disagrees with the negative count")
    out += _recovery_macros()
    return out


def separability_macros(path=os.path.join("docs", "results", "span_symmetry.csv")):
    """How badly an independence assumption would misprice the inversion rate.

    `analyze_span_symmetry.py` already convolves the two measured margins to get the rate that
    would follow if the delivery and the acknowledgment lag were independent, and stores it
    beside the observed rate. Nothing has ever read it. It is the numerical form of the
    objection R. Duvignau raised against the separable model, and it is decisive.

    The overshoot is the **median of the per-condition ratios**, not the ratio of the medians.
    Those are 12.4x and 21.3x here, and the second is not an estimator of anything: it divides
    one condition's typical prediction by a different condition's typical observation. The
    same mistake was caught once already in this pipeline, against `reportedFraction`, which
    is why the guard below is a gate and not a comment.

    Conditions with no observed negatives at all are excluded from the ratio, because the
    ratio is undefined there. That makes the figure conservative rather than generous: in
    those the independence model predicts a nonzero rate where none occurred, so the true
    overshoot is unbounded, and dropping them can only pull the median down.
    """
    import csv as _csv
    import statistics as _st
    try:
        with open(path, encoding="utf-8") as fh:
            rows = list(_csv.DictReader(fh))
    except OSError:
        return []
    obs, pred, ratios, over = [], [], [], 0
    for r in rows:
        try:
            o = float(r["neg_frac_obs"])
            p = float(r["neg_frac_pred_indep"])
        except (KeyError, TypeError, ValueError):
            continue
        obs.append(o)
        pred.append(p)
        if p > o:
            over += 1
        if o > 0:
            ratios.append(p / o)
    if not obs or not ratios:
        return []
    return [
        ("indepConditions", str(len(obs))),
        ("indepOvershootConditions", str(over)),
        ("indepOvershoot", "%.1f" % _st.median(ratios)),
        ("indepOvershootN", str(len(ratios))),
        ("indepMedianObs", "%.2f" % (100.0 * _st.median(obs))),
        ("indepMedianPred", "%.1f" % (100.0 * _st.median(pred))),
    ]


def _recovery_macros(path=os.path.join("docs", "results", "span_symmetry.csv")):
    """The remedy's accuracy, split by gate outcome.

    Reported on the rejected conditions as well as the accepted ones on purpose. A
    correction validated only where the check already passes has been validated on the
    population that did not need it.
    """
    import csv as _csv
    import statistics as _st
    try:
        with open(path, encoding="utf-8") as fh:
            rows = list(_csv.DictReader(fh))
    except OSError:
        return []
    out = []
    for suffix, name in (("#pass", "Pass"), ("#fail", "Fail")):
        rel = [abs(float(r["recovery_err_us"])) / float(r["median_D_us"]) * 100.0
               for r in rows
               if r["condition"].endswith(suffix) and float(r["median_D_us"])]
        if rel:
            out.append(("recoveryErr" + name, "%.1f" % _st.median(rel)))
    rho = [float(r["rho_DA"]) for r in rows if r["rho_DA"] not in ("", "nan")]
    if rho:
        out.append(("spanRhoMedian", "%.2f" % _st.median(rho)))

    # The displacement's own scale, and what it does to a reported number.
    #
    # A is a SCHEDULING quantity: it is set by how long a runnable thread waits for a core,
    # not by how far the message travelled. That is the whole content of the 1/D law -- the
    # numerator does not grow when the path does, so the relative error falls as the path
    # lengthens, and the two brokers' A values differ because their CLIENTS differ, not
    # because the brokers do.
    lag = [float(r["median_A_us"]) for r in rows if r["median_A_us"]]
    if lag:
        out.append(("ackLagMedianUs", "%.0f" % _st.median(lag)))
    frac = [float(r["median_S_us"]) / float(r["median_D_us"])
            for r in rows if float(r["median_D_us"])]
    if frac:
        m = _st.median(frac)
        out += [("reportedFraction", "%.0f" % (100.0 * m)),
                ("understateFactor", "%.1f" % (1.0 / m))]
    per = {}
    for r in rows:
        if float(r["median_D_us"]):
            per.setdefault(r["condition"].split("_")[0], []).append(
                (float(r["median_D_us"]), float(r["median_S_us"])))
    if {"kafka", "redis"} <= set(per):
        dk = _st.median([d for d, _ in per["kafka"]])
        sk = _st.median([s for _, s in per["kafka"]])
        dr = _st.median([d for d, _ in per["redis"]])
        sr = _st.median([s for _, s in per["redis"]])
        if dr and sr and dk / dr:
            out += [("gapTrue", "%.2f" % (dk / dr)),
                    ("gapReported", "%.2f" % (sk / sr)),
                    ("gapDistortion", "%.2f" % ((sk / sr) / (dk / dr)))]
            # An interval on the distortion, resampling CONDITIONS rather than events:
            # conditions are the exchangeable unit here, since every event inside one shares
            # a broker, a sender count and a feed count. A referee asked for the factor to
            # be quoted as a number with an interval rather than as a number, and a factor
            # this close to 2 invites exactly that question.
            import random as _random
            rng = _random.Random(20260831)
            boots = []
            for _ in range(4000):
                ks = [_random.Random(rng.random()).choice(per["kafka"]) for _ in per["kafka"]]
                rs = [_random.Random(rng.random()).choice(per["redis"]) for _ in per["redis"]]
                bdk = _st.median([d for d, _ in ks])
                bsk = _st.median([s for _, s in ks])
                bdr = _st.median([d for d, _ in rs])
                bsr = _st.median([s for _, s in rs])
                if bdr and bsr and bdk:
                    boots.append((bsk / bsr) / (bdk / bdr))
            # There was a `len(boots) > 100` guard here until round 42, and it could not
            # fire. A resample is dropped only when its redis span median lands on zero,
            # which needs more than half the resampled conditions to be zero-span -- and the
            # `sr` test above has already established that the real median is not zero, so
            # fewer than half of them are. That bounds the drop rate below a half, and 4000
            # draws cannot leave under 100. A branch nothing can take is not a safeguard.
            #
            # Nothing replaces it on purpose. If `boots` were ever empty the indexing below
            # raises, which is the behaviour this module wants: the macro is consumed by
            # \gapDistortionCI in Section VI-B, so silently declining to emit it would fail
            # the LaTeX build one step later with a worse error than the one raised here.
            boots.sort()
            lo = boots[int(0.025 * len(boots))]
            hi = boots[int(0.975 * len(boots))]
            out.append(("gapDistortionCI", "%.2f$--$%.2f" % (lo, hi)))
    return out


def paired_gap_macros(path=os.path.join("docs", "results", "span_symmetry.csv")):
    """The two-broker gap distortion, computed by pairing like with like.

    The published `gapDistortion` divides Kafka's median condition by Redis's median
    condition. Those are different workloads: Kafka ran 32 conditions, Redis 38, and only
    24 have a counterpart. Comparing the two medians therefore compares a Kafka workload
    against a Redis workload chosen independently of it, and that -- not the use of a median
    -- is what made the figure move from 1.98 to 1.05 depending on the aggregator.

    Pairing on the workload removes it. For each (sender count, feed count) present on both
    brokers the distortion is

        (S_k / S_r) / (D_k / D_r)

    which, by an identity that holds to 4e-16 over all 24 pairs, equals the ratio of the two
    brokers' own reported fractions, (S_k/D_k) / (S_r/D_r). The distortion is not a separate
    phenomenon: it is this paper's 24% headline applied per broker and divided.

    The paired estimator carries its own distribution, so the spread is an interquartile
    range over pairs rather than a bootstrap that resamples conditions while holding the
    aggregator and the bin width fixed -- which propagated one source of uncertainty out of
    three. It is also stable where the old one was not: 1.68 to 1.75 across both bin widths
    tried and both ways of handling the gate, against 1.05 to 1.98 unpaired.

    And it reports the direction. In about a fifth of matched workloads the instrument
    understates the gap instead of inflating it, which the published claim does not admit.
    """
    import csv as _csv
    import re as _re
    import statistics as _st
    try:
        with open(path, encoding="utf-8") as fh:
            rows = list(_csv.DictReader(fh))
    except OSError:
        return []
    per = {}
    for r in rows:
        m = _re.match(r"(\w+?)_n(\d+)_feed(\d+)(#(pass|fail))?$", r["condition"])
        if not m:
            continue
        try:
            s, d = float(r["median_S_us"]), float(r["median_D_us"])
        except (KeyError, TypeError, ValueError):
            continue
        if d <= 0:
            continue
        per.setdefault(m.group(1), {})[(m.group(2), m.group(3), m.group(5) or "")] = (s, d)
    if not {"kafka", "redis"} <= set(per):
        return []
    shared = sorted(set(per["kafka"]) & set(per["redis"]))
    dist = []
    for k in shared:
        (sk, dk), (sr, dr) = per["kafka"][k], per["redis"][k]
        if sr > 0 and dr > 0 and dk > 0:
            dist.append((sk / sr) / (dk / dr))
    if len(dist) < 4:
        return []
    dist.sort()
    n = len(dist)
    lo = dist[n // 4]
    hi = dist[(3 * n) // 4]
    up = sum(1 for x in dist if x > 1.0)
    return [
        ("gapDistortionPaired", "%.1f" % _st.median(dist)),
        ("gapDistortionPairedIQR", "%.1f$--$%.1f" % (lo, hi)),
        ("gapDistortionPairs", str(n)),
        ("gapDistortionInflates", "%.0f" % (100.0 * up / n)),
        ("gapDistortionDeflates", "%.0f" % (100.0 * (n - up) / n)),
    ]


